"""Shared response primitives: enums, error envelope, health payload."""

from __future__ import annotations

from datetime import date, datetime
from enum import Enum
from typing import Any, Literal

from pydantic import BaseModel, ConfigDict, Field


class StrictModel(BaseModel):
    """Base for response models: reject unknown fields, allow ORM objects."""

    model_config = ConfigDict(extra="forbid", from_attributes=True)


class RiskLevel(str, Enum):
    """Expiry-risk severity. Derived by an explicit documented rule, never ad hoc."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    CRITICAL = "critical"


class RecommendationAction(str, Enum):
    """Closed vocabulary of operational recommendations."""

    REORDER = "reorder"
    SUFFICIENT = "sufficient"
    OVERSTOCK = "overstock"
    EXPIRY_EXPOSURE = "expiry_exposure"
    URGENT_ROTATION = "urgent_rotation"
    MONITOR = "monitor"


class Priority(str, Enum):
    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"


class ErrorDetail(StrictModel):
    code: str = Field(
        ..., description="Stable machine-readable error code.", examples=["not_found"]
    )
    message: str = Field(..., description="Human-readable explanation.")
    details: dict[str, Any] = Field(
        default_factory=dict, description="Structured context (never secrets)."
    )


class ErrorResponse(StrictModel):
    """The one and only error envelope. Every non-2xx response matches this."""

    error: ErrorDetail


class ComponentHealth(StrictModel):
    name: str
    status: Literal["ok", "degraded", "unavailable"]
    detail: str | None = None


class HealthResponse(StrictModel):
    status: Literal["ok", "degraded", "unavailable"]
    app: str
    version: str
    environment: str
    checked_at_utc: datetime
    components: list[ComponentHealth]


class DataFreshness(StrictModel):
    """Where the served numbers come from. Surfaced so nobody mistakes a
    synthetic/demo dataset for live pharmacy data."""

    dataset_version: str
    prediction_origin: date
    horizon_days: int
    is_synthetic: bool = True
    provenance_note: str = Field(
        default=(
            "Synthetic data generated by the MediStock AI simulator. "
            "Not real pharmacy transaction data."
        )
    )
